#!/usr/bin/env python3
"""Slice a 6x6 RGBA sheet and build a self-contained MUGEN SFF v1 archive."""
from pathlib import Path
import io
import json
import struct
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
CHAR = ROOT / 'chars/femboygary'

def build():
    sheet = Image.open(ROOT / 'assets/snail-sheet.png').convert('RGBA')
    w, h = sheet.size
    if w % 6 or h % 6:
        raise ValueError('Sheet must have six equal columns and rows')
    cw, ch = w // 6, h // 6
    frames = []
    out = ROOT / 'assets/frames'
    out.mkdir(exist_ok=True)
    # Palette entry zero is reserved for transparency by MUGEN.
    palette_source = sheet.convert('RGB').quantize(colors=255)
    palette = [255, 0, 255] + palette_source.getpalette()[:765]
    palette_image = Image.new('P', (1, 1))
    palette_image.putpalette(palette)
    manifest = []
    for row in range(6):
        for col in range(6):
            sprite = sheet.crop((col*cw, row*ch, (col+1)*cw, (row+1)*ch))
            sprite = sprite.resize((256, 256), Image.Resampling.NEAREST)
            sprite.save(out / f'{row}-{col}.png')
            # Quantize opaque colors with the same global palette, then shift
            # indices by one. Transparency never competes with a visible color.
            rgb = sprite.convert('RGB').quantize(palette=palette_source, dither=Image.Dither.NONE)
            indexed = Image.new('P', sprite.size)
            indexed.putpalette(palette)
            indexed.putdata([0 if a < 128 else min(i+1,255) for i,a in zip(rgb.getdata(),sprite.getchannel('A').getdata())])
            data = io.BytesIO()
            indexed.save(data, format='PCX')
            group, number = row, col
            frames.append((group, number, 128, 232, data.getvalue()))
            manifest.append(dict(group=group, image=number, file=f'{row}-{col}.png', axis=[128,232]))
    # Standard portrait groups expected by character select and lifebars.
    for group, size in [(9000,(25,25)), (9000,(120,140))]:
        portrait = Image.open(out / '0-0.png').convert('RGBA')
        box = portrait.getbbox()
        if box: portrait = portrait.crop(box)
        portrait.thumbnail(size,Image.Resampling.NEAREST)
        canvas = Image.new('RGBA',size)
        canvas.alpha_composite(portrait,((size[0]-portrait.width)//2,(size[1]-portrait.height)//2))
        rgb = canvas.convert('RGB').quantize(palette=palette_source,dither=Image.Dither.NONE)
        indexed=Image.new('P',size); indexed.putpalette(palette)
        indexed.putdata([0 if a<128 else min(i+1,255) for i,a in zip(rgb.getdata(),canvas.getchannel('A').getdata())])
        data=io.BytesIO(); indexed.save(data,format='PCX')
        frames.append((group,0 if size[0]==25 else 1,0,0,data.getvalue()))
    header = b'ElecbyteSpr\0' + bytes([0,1,0,1])
    header += struct.pack('<IIIIB3s',7,len(frames),512,32,0,b'\0'*3)
    header += b'Generated by build_character.py'.ljust(476,b'\0')
    assert len(header)==512
    archive=bytearray(header)
    for index,(group,number,x,y,data) in enumerate(frames):
        next_offset=len(archive)+32+len(data) if index+1<len(frames) else 0
        archive.extend(struct.pack('<IIhhHHHB13s',next_offset,len(data),x,y,group,number,0,0,b'\0'*13))
        archive.extend(data)
    (CHAR/'femboygary.sff').write_bytes(archive)
    (ROOT/'assets/frames.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Built {len(frames)} sprites, {len(archive)} bytes')

if __name__ == '__main__':
    build()
